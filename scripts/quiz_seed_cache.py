def cache_key(title: str) -> str:
    """复刻上游 query_all 的键规范化：去前导数字、去末尾（x.x分）。"""
    key = re.sub(r"^\d+", "", title or "")
    return re.sub(r"（\d+\.\d+分）$", "", key)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--course-id", default="250292520")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--account", default="acc_01", help="账号 ID（决定 cache.json 落在哪个工作区）")
    args = ap.parse_args()

    global ACCOUNT_DIR
    ACCOUNT_DIR = ROOT / "accounts" / args.account / "upstream" / "chaoxing"
    # 必须重新 chdir：CacheDAO 的 cache.json 是 CWD 相对路径，
    # 只改变量不切目录会把缓存写进别的账号（踩过）
    os.chdir(ACCOUNT_DIR)

    src = ROOT / "runs" / f"quiz_prefetch_{args.course_id}.json"
    data = json.loads(src.read_text(encoding="utf-8"))

    from api.answer import CacheDAO  # noqa: PLC0415

    dao = CacheDAO()
    matched, missing, total = 0, [], 0
    for qz in data["quizzes"]:
        for q in qz["questions"]:
            total += 1
            title = q.get("title") or ""
            hit = None
            for keyword, answer in TABLE:
                if keyword in title:
                    hit = answer
                    break
            if hit is None:
                missing.append((qz["chapter"], title[:60], q.get("type")))
                continue
            value = "\n".join(hit) if isinstance(hit, list) else str(hit)
            key = cache_key(title)
            if not args.dry_run:
                dao.add_cache(key, value)
            matched += 1

    # 同时导出给 shim 的"已知答案"表：上游重做轮会绕过它自己的 CacheDAO，
    # 那时只有 shim 认得答案才能秒答（否则每题空等到超时）
    known_path = ROOT / "runs" / "answer" / "known_answers.json"
    known_path.parent.mkdir(parents=True, exist_ok=True)
    known_rows = [
        {
            "contains": keyword,
            "answer": "\n".join(ans) if isinstance(ans, list) else str(ans),
        }
        for keyword, ans in TABLE
    ]
    if not args.dry_run:
        known_path.write_text(
            json.dumps(known_rows, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        print(f"已知答案表 → {known_path}（{len(known_rows)} 条）")

    print(f"题目 {total} 道 → 写入缓存 {matched} 道")
    if missing:
        print(f"\n未覆盖 {len(missing)} 道（跑批时上游会随机作答）：")
        for chapter, title, qtype in missing:
            print(f"  - [{qtype}] {chapter}: {title}")
    if not args.dry_run:
        cache_file = Path(dao.cache_file)
        print(f"\n缓存文件：{cache_file.resolve()}（{len(json.loads(cache_file.read_text(encoding='utf-8')))} 条）")


if __name__ == "__main__":
    main()
